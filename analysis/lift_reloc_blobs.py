#!/usr/bin/env python3
"""Lift the position-independent EBOOT code GoW:A's BatchJobList jobs stage in local store.

The BatchJobList jobs (wid 7, job module 759d) copy four EBOOT blobs into local store and
run them there, each load at a new 16-byte-aligned address (one capture: 299 loads, 299
addresses), so a lift per placement (lift_edge_frags.py) cannot cover them. The code is
position-independent (pc-getter `brsl $rX, .+4` plus offsets, no absolute branches or
lqa/stqa), so each blob is lifted ONCE at a canonical LS base with spu_lifter.py --reloc
and registered with spu_overlay_register_region_reloc(): any GET of the blob makes that
copy resident, and dispatch runs the canonical lift with ctx->reloc_delta set.

Extra function entries come from SPU_INTERP_MISS logs: a miss inside resident relocatable
code is reported with the blob's image id and the canonical pc
  [interp-miss]   wid=7 img=<image> pc=0x<canonical pc> ...
and the entries of an existing lift are passed again, so a re-lift keeps them.
Output: <port>/spu/relocblob_<ea>/spu_recomp.{c,h} and <port>/spu/relocblobs_register.c
(image ids 900+). Derived from the game: keep it out of the repository.

Usage: python analysis/lift_reloc_blobs.py [--merge-chunks] <EBOOT.elf> <port_dir> <ps3recomp_dir> [miss log...]
"""
import os, re, subprocess, sys

# (source EA, bytes): the largest GET seen of each (x112; 0x6D66B0 is also loaded as 0xB70 bytes)
BLOBS = [(0x716730, 0x2450), (0x6D66B0, 0xB80), (0x6AC8B0, 0x28E0), (0x6AF1B0, 0x32E0)]
CANON = 0x20000       # canonical LS base of every blob's lift (images differ, so they can share it)
IMAGE_BASE = 900

def main():
    args = [a for a in sys.argv[1:] if a != "--merge-chunks"]
    merge = len(args) != len(sys.argv) - 1
    elf, port, sdk, logs = args[0], args[1], args[2], args[3:]
    data = open(elf, "rb").read()
    py = sys.executable
    misses = {}   # image id -> canonical pcs
    for log in logs:
        t = open(log, encoding="latin1").read()
        for img, pc in re.findall(r"\[interp-miss\]\s+wid=-?\d+ img=(\d+) pc=0x([0-9A-F]+)", t):
            misses.setdefault(int(img), set()).add(int(pc, 16))
    out_dir = os.path.join(port, "spu")
    reg = []
    for k, (ea, n) in enumerate(BLOBS):
        iid = IMAGE_BASE + k
        name = f"relocblob_{ea:06x}"
        d = os.path.join(out_dir, name)
        os.makedirs(d, exist_ok=True)
        raw, elf_out = os.path.join(d, name + ".bin"), os.path.join(d, name + ".elf")
        open(raw, "wb").write(data[ea - 0x10000: ea - 0x10000 + n])
        subprocess.check_call([py, os.path.join(sdk, "tools", "wrap_spu_elf.py"), raw,
                               "--base", hex(CANON), "--entry", hex(CANON), "--out", elf_out],
                              stdout=subprocess.DEVNULL)
        cmd = [py, os.path.join(sdk, "tools", "spu_lifter.py"), "--reloc", "--auto-functions", elf_out,
               "--symbol-prefix", name + "_", "-o", d]
        if merge:
            cmd += ["--merge-chunks"]
        old = os.path.join(d, "spu_recomp.c")
        kept = {int(a, 16) for a in re.findall(r"^void \w+_spu_func_([0-9A-F]{8})\(", open(old, encoding="utf8").read(), re.M)} \
            if os.path.exists(old) else set()
        extra = sorted({m for m in misses.get(iid, set()) | kept if CANON <= m < CANON + n})
        if extra:
            cmd += ["--extra-funcs", ",".join(hex(m) for m in extra)]
        subprocess.check_call(cmd, stdout=subprocess.DEVNULL)
        for fn in ("spu_recomp.c", "spu_recomp.h"):
            p = os.path.join(d, fn)
            s = open(p, encoding="utf8").read()
            s = s.replace('"../../runtime/spu/spu_context.h"', '"spu_context.h"')
            s = s.replace('"../../runtime/spu/spu_helpers.h"', '"spu_helpers.h"')
            open(p, "w", encoding="utf8", newline="\n").write(s)
        os.remove(raw); os.remove(elf_out)
        reg.append((name, ea, n, iid))
        print(f"{name}: ea 0x{ea:06X} size 0x{n:X} at canonical LS 0x{CANON:05X}, image {iid}"
              + (f" (+{len(extra)} entries)" if extra else ""))
    L = ["/* GENERATED by analysis/lift_reloc_blobs.py -- BatchJobList's position-independent",
         " * code blobs, each lifted once at a canonical base (spu_lifter.py --reloc). */",
         "#include <stdint.h>", "",
         "extern void spu_begin_image(int image_id);",
         "extern void spu_overlay_register_region_reloc(uint32_t ea, uint32_t span, uint32_t canon, int image_id);", ""]
    L += [f"extern void {name}_spu_recomp_register(void);" for name, *_ in reg]
    L += ["", "void gow_relocblobs_register_all(void)", "{"]
    for name, ea, n, iid in reg:
        L.append(f"    spu_begin_image({iid}); {name}_spu_recomp_register();")
        L.append(f"    spu_overlay_register_region_reloc(0x{ea:08X}u, 0x{n:X}u, 0x{CANON:05X}u, {iid});")
    L += ["    spu_begin_image(0);", "}", "",
          "__attribute__((constructor)) static void gow_relocblobs_register_ctor(void)", "{",
          "    gow_relocblobs_register_all();", "}", ""]
    open(os.path.join(out_dir, "relocblobs_register.c"), "w", encoding="utf8", newline="\n").write("\n".join(L))
    print(f"{len(reg)} blobs -> {os.path.join(out_dir, 'relocblobs_register.c')}")

if __name__ == "__main__":
    main()
