#!/usr/bin/env python3
"""Lift raw SPU blobs from the decrypted EBOOT into the port's spu/ tree.

For each entry of images.json ({name, va, size, base, entry, id}):
  1. cut `size` bytes at guest VA `va` out of the EBOOT ELF (text segment maps
     file offset = va - 0x10000)
  2. wrap them as an SPU ELF (wrap_spu_elf.py) at LS `base`, entry `entry`
  3. lift with spu_lifter.py --auto-functions under a per-image symbol prefix
  4. rewrite the two depth-sensitive includes to bare names
  5. emit spu_workloads.c registering every image under the runtime's FNV-1a-64
     fingerprint of the RAW blob (what spurs_resolve_pm computes over guest bytes)

Usage: make_spu_port.py <EBOOT.elf> <images.json> <port_dir> <ps3recomp_dir>
"""
import json, os, re, subprocess, sys

elf_path, images_json, port_dir, sdk = sys.argv[1:5]
py = sys.executable
data = open(elf_path, "rb").read()
imgs = json.load(open(images_json))
work = os.path.join(port_dir, "spu")
os.makedirs(work, exist_ok=True)


def fnv(b):
    h = 1469598103934665603
    for x in b:
        h ^= x
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


reg = []
for im in imgs:
    name, size = im["name"], int(str(im["size"]), 0)
    base, entry, iid = int(str(im["base"]), 0), int(str(im["entry"]), 0), int(im["id"])
    if "file" in im:
        # blob lives in another file (e.g. the SPU kernel ELF embedded in the
        # relocated libsre image); "foff" is the offset inside it
        foff = int(str(im.get("foff", 0)), 0)
        va = foff
        blob = open(os.path.expandvars(im["file"]), "rb").read()[foff:foff + size]
    else:
        va = int(str(im["va"]), 0)
        off = va - 0x10000
        blob = data[off:off + size]
    assert len(blob) == size, name
    d = os.path.join(work, name)
    os.makedirs(d, exist_ok=True)
    raw = os.path.join(d, name + ".bin")
    open(raw, "wb").write(blob)
    elf = os.path.join(d, name + ".elf")
    if blob[:4] == b"\x7fELF":
        open(elf, "wb").write(blob)          # already an SPU ELF: no wrapping
    else:
        subprocess.check_call([py, os.path.join(sdk, "tools", "wrap_spu_elf.py"), raw,
                               "--base", hex(base), "--entry", hex(entry), "--out", elf],
                              stdout=subprocess.DEVNULL)
    prefix = f"{name}_"
    cmd = [py, os.path.join(sdk, "tools", "spu_lifter.py"),
           "--auto-functions", elf, "--symbol-prefix", prefix, "-o", d]
    # Optional "extra": LS addresses reached only indirectly (interrupt returns,
    # computed branches) -- found with the runtime's SPU_INTERP_MISS histogram.
    if im.get("extra"):
        cmd += ["--extra-funcs", ",".join(im["extra"])]
    subprocess.check_call(cmd, stdout=subprocess.DEVNULL)
    for fn in ("spu_recomp.c", "spu_recomp.h"):
        p = os.path.join(d, fn)
        t = open(p, encoding="utf8").read()
        t = t.replace('"../../runtime/spu/spu_context.h"', '"spu_context.h"')
        t = t.replace('"../../runtime/spu/spu_helpers.h"', '"spu_helpers.h"')
        open(p, "w", encoding="utf8", newline="\n").write(t)
    reg.append((name, prefix, fnv(blob), entry, iid))
    print(f"{name}: {size} B @ VA 0x{va:X} -> LS 0x{base:X}, fp 0x{fnv(blob):016X}, image id {iid}")

L = ['/* GENERATED by analysis/make_spu_port.py -- registers the lifted SPU images by',
     ' * FNV-1a-64 fingerprint of the raw blob. */',
     '#include "spu_workload.h"', '', 'extern void spu_begin_image(int image_id);', '']
for name, prefix, fp, ent, iid in reg:
    L.append(f"extern void {prefix}spu_func_{ent:08X}(spu_context*);")
    L.append(f"extern void {prefix}spu_recomp_register(void);")
L += ['', 'void gow_spu_register_all(void)', '{']
for name, prefix, fp, ent, iid in reg:
    L.append(f"    spu_begin_image({iid}); {prefix}spu_recomp_register();")
    L.append(f'    spu_workload_register_img(0x{fp:016X}ULL, {prefix}spu_func_{ent:08X}, {iid}, "{name}");')
L += ['    spu_begin_image(0);', '}', '',
      '__attribute__((constructor)) static void gow_spu_register_all_ctor(void)', '{',
      '    gow_spu_register_all();', '}', '']
open(os.path.join(work, "spu_workloads.c"), "w", encoding="utf8", newline="\n").write("\n".join(L))
print("wrote", os.path.join(work, "spu_workloads.c"))
