"""gen_edge_e550_body.py <spu_recomp.c> <out.h>: the E550 loop body macros for port/gow_edge_native.c.

The native E550 loop's v1 (and the last iteration of v2/v3) runs the lifted loop body itself, with the SPU
registers in C locals. That body is game code, so the repo does not carry it: this script takes it from the
d935 module's production lift (jobmod_d93503647dd8_e6d98/spu_recomp.c, the E550 function's copy of
loc_0000EC08 up to its back edge) and writes gow_edge_e550_body.h into the build tree:

  GOW_E550_REGS()           u128 locals for every register the body uses
  GOW_E550_LOAD_INPUTS()    rN = g[N] for every register read before the body writes it
  GOW_E550_STORE_OUTPUTS()  g[N] = rN for every register the body writes
  GOW_E550_BODY()           the statements: ctx->gpr[N] -> rN, spu_ls_read128/write128(ctx, ...) -> LD/ST(...)

The port's CMakeLists.txt runs it whenever the lift changes; gow_edge_native.c includes the header.
A lab lift works as well (a probe wrapper renames E550 to _impl, --blocks counts at labels).
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
lines = open(src, newline="").read().replace("\r\n", "\n").split("\n")
fn = next(i for i, l in enumerate(lines) if re.match(r"^void \w+_spu_func_0000E550(?:_impl)?\(spu_context\* ctx\) \{", l))
start = next(i for i in range(fn, len(lines)) if lines[i].strip().startswith("loc_0000EC08:"))
end = next(i for i in range(start, len(lines)) if lines[i].strip() == "if (ctx->gpr[48]._u32[0] != 0) goto loc_0000EC08;")
body = [l.strip() for l in lines[start + 1:end] if l.strip() and l.strip() != "/* branch hint (ignored) */;"]

GPR = re.compile(r"ctx->gpr\[(\d+)\]")
ASSIGN = re.compile(r"^ctx->gpr\[(\d+)\] = (.*);$")
read, written, out = [], [], []
for s in body:
    m = ASSIGN.match(s)
    rhs = m.group(2) if m else s
    if not m and not s.startswith("spu_ls_write128(ctx,"):
        sys.exit(f"unexpected statement in the loop body: {s}")
    for n in map(int, GPR.findall(rhs)):
        if n not in written and n not in read:
            read.append(n)
    if m and int(m.group(1)) not in written:
        written.append(int(m.group(1)))
    s = s.replace("spu_ls_read128(ctx, ", "LD(").replace("spu_ls_write128(ctx, ", "ST(")
    out.append(GPR.sub(lambda g: f"r{g.group(1)}", s))
if "ctx" in " ".join(out):
    sys.exit("ctx left in the body")

regs = sorted(set(read) | set(written))
w = max(len(s) for s in out)
h = ["/* generated by gen_edge_e550_body.py from the d935 lift -- game code, do not commit */",
     "#define GOW_E550_REGS() u128 " + ", ".join(f"r{n}" for n in regs) + ";", "",
     "#define GOW_E550_LOAD_INPUTS() \\"] + [f"    r{n} = g[{n}]; \\" for n in sorted(read)] + ["", "",
     "#define GOW_E550_STORE_OUTPUTS() \\"] + [f"    g[{n}] = r{n}; \\" for n in sorted(written)] + ["", "",
     "#define GOW_E550_BODY() \\"] + [f"    {s.ljust(w)} \\" for s in out] + ["", ""]
open(dst, "w", newline="\n").write("\n".join(h))
print(f"{len(out)} statements, {len(read)} inputs, {len(written)} outputs -> {dst}")
